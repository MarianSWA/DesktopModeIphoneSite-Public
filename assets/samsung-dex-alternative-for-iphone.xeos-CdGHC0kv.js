  <p>La diferencia real está en la sexta fila. DeX forma parte del propio Android, así que cualquier app de Android puede abrirse en una ventana. En iOS ninguna app puede ejecutar otra dentro. XeOS lo compensa con sus propias apps y con toda la web: Google Docs y Hojas de cálculo, Office en la web, Gmail, YouTube, Netflix y casi todo lo que abrirías en un portátil sobre la mesa. Cualquiera de esos sitios se puede instalar en el dock y abrirse en su propia ventana, como una app.</p>

