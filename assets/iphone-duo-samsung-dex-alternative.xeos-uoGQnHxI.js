  <h2 id="where-xeos-comes-in">Where XeOS comes in</h2>

  <p><strong>XeOS</strong> is the desktop the Duo is missing. It takes over the external display and draws its own environment there at the display's native resolution, so the picture fills the screen with no black bars. You get windows, a dock, a file manager, a desktop browser and a set of built-in apps.</p>

  <p>With the 2.8 update, the Duo gets something DeX doesn't normally offer a phone. The inner screen doesn't just act as a touchpad: XeOS can treat it as a second display with its own windows. Keep your main work on the monitor and a video, a chat or reference material on the Duo, and drag windows across when you want them bigger or out of the way. Pair a mouse and a single pointer moves across both screens.</p>

